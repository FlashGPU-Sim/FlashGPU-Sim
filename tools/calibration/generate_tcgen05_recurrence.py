#!/usr/bin/env python3
"""Generate the exact B200 dense MMA recurrence lookup; no interpolation.

The checked-in CSV is extracted from b200-tensor-core-summary-20261013 /
shape-throughput.csv, with original case IDs and T128/T256 preserved.
Only one-owner, one-chain, default-collector, K/K-major measurements qualify.
Regenerate after changing the CSV; --check verifies the checked-in header.
"""
import argparse
import csv
import hashlib
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'data/calibration/b200-tcgen05-recurrence.csv'
TARGET = ROOT / 'src/gpgpu-sim/flash/tcgen05/native_recurrence_table.h'

def generate():
    entries = {}
    with SOURCE.open() as stream:
        for row in csv.DictReader(stream):
            profile, group, m, n, k, tmem, ws = (int(row[x]) for x in
                ('profile', 'group', 'm', 'n', 'k', 'tmem_a', 'ws'))
            assert 0 < profile < 16 and group in (1, 2)
            assert 0 < m < 512 and 0 < n < 512 and 0 < k < 256
            assert tmem in (0, 1) and ws in (0, 1)
            period = (float(row['t256']) - float(row['t128'])) / 128
            assert math.isfinite(period) and period > 0
            assert abs(period - float(row['cycles_per_mma'])) < 1e-8
            key = profile << 30 | group << 28 | tmem << 27 | ws << 26 | m << 17 | n << 8 | k
            assert key not in entries, ('duplicate measurement key', row)
            entries[key] = math.ceil(period)
    lines = ['// Generated by tools/calibration/generate_tcgen05_recurrence.py.',
             '// Source CSV SHA256:',
             '// ' + hashlib.sha256(SOURCE.read_bytes()).hexdigest(), '',
             '// Dense B200, one owner/chain, K/K-major, no collector reuse.',
             '// {packed measurement key, ceil((T256-T128)/128)}',
             'static constexpr struct {',
             '  uint64_t key;', '  unsigned cycles;',
             '} kB200Recurrence[] = {',
             '    // clang-format off']
    lines += [f'    {{{key}ull, {cycles}}},' for key, cycles in sorted(entries.items())]
    return '\n'.join(lines + ['    // clang-format on', '};', ''])


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    result = generate()
    if args.check:
        if TARGET.read_text() != result:
            raise SystemExit('Stale recurrence table; regenerate it')
    else:
        TARGET.write_text(result)
